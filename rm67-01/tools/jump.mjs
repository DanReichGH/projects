import { createRequire } from "node:module";
import { pathToFileURL } from "node:url";
import { resolve } from "node:path";
const require = createRequire("/opt/node-tools/node_modules/");
const { chromium } = require("playwright");
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, deviceScaleFactor: 2 });
const errs = [];
page.on("pageerror", (e) => errs.push(e.message));
page.on("console", (m) => m.type() === "error" && errs.push(m.text()));
await page.goto(pathToFileURL(resolve("rm67-01.html")).href);
await page.waitForTimeout(1000);
await page.evaluate(() => __rm.manual());
const st = () => page.evaluate(() => { const R = __rm.model.read(__rm.state.S); return { cur: __rm.state.cur + 1, reserveH: +R.reserveH.toFixed(2), running: R.running, lift: +__rm.state.V.lift.toFixed(2), armOut: +__rm.state.V.armOut.toFixed(2), fn: __rm.state.S.fn, date: R.date, hint: document.querySelector("#hint").textContent.slice(0, 60), states: [...document.querySelectorAll("#steps button")].map((b) => b.dataset.state[0]).join(""), disabled: [...document.querySelectorAll("#steps button")].filter((b) => b.disabled).length }; });
const t0 = Date.now();
await page.click("#steps button[data-i='5']");
console.log("jump to 6 from fresh:", JSON.stringify(await st()), `(${Date.now() - t0} ms)`);
await page.evaluate(() => __rm.advance(1500));
const card = page.locator(".card");
const box = await card.boundingBox();
await page.screenshot({ path: "shots/front6.png", clip: { x: box.x + box.width * 0.24, y: box.y + box.height * 0.24, width: box.width * 0.24, height: box.height * 0.26 } });
await page.evaluate(() => __rm.advance(1500));
await page.click("#steps button[data-i='2']");
console.log("jump back to 3 mid-step:", JSON.stringify(await st()));
await page.click("#steps button[data-i='9']");
await page.evaluate(() => __rm.advance(3000));
console.log("jump to 10:", JSON.stringify(await st()));
await page.click("#steps button[data-i='0']");
console.log("jump to 1:", JSON.stringify(await st()));
console.log("errors:", errs.length ? errs : "none");
await browser.close();
