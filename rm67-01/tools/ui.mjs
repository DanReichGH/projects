import { createRequire } from "node:module";
import { pathToFileURL } from "node:url";
import { resolve } from "node:path";
const require = createRequire("/opt/node-tools/node_modules/");
const { chromium } = require("playwright");
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
const page = await ctx.newPage();
const url = pathToFileURL(resolve("rm67-01.html")).href;
await page.goto(url);
await page.waitForTimeout(800);
const enabled = await page.$$eval("#steps button", (b) => b.map((x) => !x.disabled));
console.log("manual: clickable buttons", enabled.map((e, i) => (e ? i + 1 : "")).filter(Boolean), "pulse on", await page.$$eval("#steps .pulse .n", (n) => n.map((x) => x.textContent)));
await page.click("#steps button[data-i='0']");
await page.waitForTimeout(300);
console.log("after pressing 1: states", await page.$$eval("#steps button", (b) => b.slice(0, 3).map((x) => x.dataset.state)));
await page.waitForTimeout(2000);
console.log("after it ends: next clickable", await page.$$eval("#steps button", (b) => b.map((x, i) => (!x.disabled ? i + 1 : null)).filter(Boolean)), "| hint:", await page.textContent("#hint"));
await page.click(".mode button[data-mode='auto']");
await page.waitForTimeout(7000);
console.log("auto: running step", await page.$$eval("#steps button", (b) => b.findIndex((x) => x.dataset.state === "running") + 1));
await page.reload();
await page.waitForTimeout(800);
console.log("after reload mode remembered:", await page.$eval(".mode button[aria-pressed='true']", (b) => b.dataset.mode));
await page.click(".mode button[data-mode='manual']");
await page.click("#restart");
await page.waitForTimeout(300);
console.log("start over:", await page.evaluate(() => ({ next: __rm.state.next, reserve: __rm.state.S.reserve, lift: __rm.state.V.lift })));
await page.click("#act", { position: { x: 2, y: 5 } });
console.log("slider at 0:", await page.textContent("#actOut"), "|", (await page.textContent("#ledger")).replace(/\s+/g, " ").trim());
await page.click("input[value='both']");
console.log("both ways:", (await page.textContent("#ledger")).replace(/\s+/g, " ").trim());
await browser.close();
